"""Builds src/render/interior/cityCatalog.ts from the interiors catalogue zip.

Usage: python -I tools/interiors/extract_interiors.py assets/neon_dynasty_innenansichten_katalog_236.zip
Keeps only what the game uses: archetype, view type and the named zones per
building id (ids match public/sprites/catalog.json), plus the art direction
per region (identical for all buildings of a region).
"""
import json
import sys
import zipfile

src = sys.argv[1]
with zipfile.ZipFile(src) as z:
    name = next(n for n in z.namelist() if n.endswith('interiors_catalog.json'))
    data = json.loads(z.read(name).decode('utf-8'))

entries = data['buildings']
regions = {}
for e in entries:
    regions.setdefault(e['district'], e['artDirection'])
    assert regions[e['district']] == e['artDirection'], e['id']

archetypes = sorted({e['interiorArchetype'] for e in entries})
q = lambda s: json.dumps(s, ensure_ascii=False)
out = []
out.append('/**')
out.append(' * Interior catalogue of the pre-rendered city buildings (generated by')
out.append(' * tools/interiors/extract_interiors.py from the Innenansichten-Katalog; do not edit).')
out.append(' * Keys are the sprite ids of public/sprites/catalog.json.')
out.append(' */')
out.append('')
out.append('export type InteriorArchetype =')
out.extend(f'  | {q(a)}' for a in archetypes)
out[-1] += ';'
out.append('')
out.append('export interface CityInteriorZone {')
out.append('  id: string;')
out.append('  name: string;')
out.append('  interactive: boolean;')
out.append('}')
out.append('')
out.append('export interface CityInteriorEntry {')
out.append('  name: string;')
out.append('  archetype: InteriorArchetype;')
out.append("  /** 'technical_detail': an object inspection without rooms. */")
out.append('  technical: boolean;')
out.append('  zones: CityInteriorZone[];')
out.append('}')
out.append('')
out.append('export interface RegionArtDirection {')
out.append('  materials: string[];')
out.append('  lighting: string;')
out.append('  mood: string;')
out.append('}')
out.append('')
out.append('export const REGION_ART_DIRECTION: Record<string, RegionArtDirection> = {')
for r, a in regions.items():
    out.append(f"  {r}: {{ materials: {q(a['materials'])}, lighting: {q(a['lighting'])}, mood: {q(a['mood'])} }},")
out.append('};')
out.append('')
out.append('type Raw = [name: string, archetype: InteriorArchetype, technical: 0 | 1, zones: string[]];')
out.append('')
out.append('/** Zones as "id|name"; a leading "!" marks a non-interactive zone. */')
out.append('const RAW: Record<string, Raw> = {')
for e in entries:
    zs = [('' if z['interactive'] else '!') + z['id'] + '|' + z['name'] for z in e['zones']]
    tech = 1 if e['viewType'] == 'technical_detail' else 0
    out.append(f"  {q(e['id'])}: [{q(e['name'])}, {q(e['interiorArchetype'])}, {tech}, {q(zs)}],")
out.append('};')
out.append('')
out.append('const cache = new Map<string, CityInteriorEntry>();')
out.append('')
out.append('/** Interior entry for a sprite id, or null when the catalogue has none. */')
out.append('export function cityInterior(id: string): CityInteriorEntry | null {')
out.append('  const hit = cache.get(id);')
out.append('  if (hit) return hit;')
out.append('  const raw = RAW[id];')
out.append('  if (!raw) return null;')
out.append('  const zones = raw[3].map((z) => {')
out.append("    const interactive = !z.startsWith('!');")
out.append("    const [zid, name] = (interactive ? z : z.slice(1)).split('|') as [string, string];")
out.append('    return { id: zid, name, interactive };')
out.append('  });')
out.append('  const entry: CityInteriorEntry = { name: raw[0], archetype: raw[1], technical: raw[2] === 1, zones };')
out.append('  cache.set(id, entry);')
out.append('  return entry;')
out.append('}')
out.append('')
out.append('export const CITY_INTERIOR_IDS = Object.keys(RAW);')
out.append('')
with open('src/render/interior/cityCatalog.ts', 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out))
print(len(entries), 'entries,', len(archetypes), 'archetypes')
